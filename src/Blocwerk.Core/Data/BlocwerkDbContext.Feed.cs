using Blocwerk.Core.Entities;
using Microsoft.EntityFrameworkCore;

namespace Blocwerk.Core.Data;

/// <summary>
/// Model configuration of the live-update feed (<see cref="WallChange"/>, <see cref="FeedEpoch"/>). The model stays
/// provider-neutral: the Postgres-only <c>TxId</c> default and <c>NOT NULL</c> live in the migration alone, so SQLite's
/// <c>EnsureCreated</c> gets a plain nullable column.
/// </summary>
public partial class BlocwerkDbContext
{
    public DbSet<WallChange> WallChanges => Set<WallChange>();

    public DbSet<FeedEpoch> FeedEpochs => Set<FeedEpoch>();

    private static void ConfigureFeed(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<WallChange>(entity =>
        {
            entity.Property(c => c.Seq).ValueGeneratedOnAdd();

            // Generated by the database (a Postgres default added in the migration) and read back on insert, with no
            // default in the model. Not an identity column, which the provider's convention would otherwise make it.
            entity.Property(c => c.TxId)
                .ValueGeneratedOnAdd()
                .Metadata.SetValueGenerationStrategy(Npgsql.EntityFrameworkCore.PostgreSQL.Metadata.NpgsqlValueGenerationStrategy.None);

            entity.Property(c => c.Audience).HasConversion<short>();
            entity.Property(c => c.DataJson).HasColumnType("jsonb");

            entity.HasIndex(c => new { c.WallId, c.TxId, c.Seq });
            entity.HasIndex(c => new { c.AudienceUserId, c.TxId, c.Seq }).HasFilter("\"AudienceUserId\" IS NOT NULL");
            entity.HasIndex(c => c.ActorUserId).HasFilter("\"ActorUserId\" IS NOT NULL");
            entity.HasIndex(c => c.CreatedAt);
        });
    }
}
